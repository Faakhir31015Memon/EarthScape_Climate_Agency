"""Report lifecycle: queued request -> background generation -> artefact on disk.

A report is *requested* (a ``queued`` document in the ``reports`` collection), then
generated by the background executor registered as ``report.generate``. Nothing here
claims a file exists without checking the filesystem, and nothing claims a report was
generated unless the artefact was actually written and its real size measured.

Artefacts live under ``settings.REPORT_ROOT/<report_id>/<random hex>.<ext>``. The
randomised internal name means a leaked identifier cannot be guessed; the human
filename (``download_name``) is only ever presented through an authenticated,
access-checked download. There are no public URLs for report files.
"""
from __future__ import annotations

import logging
import secrets
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from apps.monitoring import import_compat

import_compat.ensure_common_api_importable()

from common import audit, storage_paths, tasks  # noqa: E402
from common.api import ADMINISTRATOR, ApiError  # noqa: E402
from common.repositories import (  # noqa: E402
    RepositoryError,
    platform_settings,
    reports as reports_repo,
    to_object_id,
    utcnow,
)
from config import env  # noqa: E402
from config.settings import REPORT_ROOT  # noqa: E402

from apps.reports import generators  # noqa: E402

logger = logging.getLogger(__name__)

STATUSES = ("queued", "running", "generated", "failed", "expired", "cancelled")
FORMATS = ("csv", "json", "pdf")
EXTENSIONS = {"csv": "csv", "json": "json", "pdf": "pdf"}
CONTENT_TYPES = {
    "csv": "text/csv; charset=utf-8",
    "json": "application/json",
    "pdf": "application/pdf",
}
TASK_NAME = "report.generate"
DEFAULT_RETENTION_DAYS = 30
FILE_PREFIX_LENGTH = 24
PRUNE_INTERVAL_SECONDS = 600
_LAST_PRUNE: Optional[datetime] = None


def retention_days() -> int:
    """Retention policy: DB-stored administrator setting wins over the env default."""
    stored = _setting_value("report_retention_days")
    for candidate in (stored, env.get_int("REPORT_RETENTION_DAYS", DEFAULT_RETENTION_DAYS)):
        try:
            value = int(candidate)
        except (TypeError, ValueError):
            continue
        if 1 <= value <= 3650:
            return value
    return DEFAULT_RETENTION_DAYS


def max_active_per_user() -> int:
    value = _setting_value("report_max_active_per_user")
    try:
        parsed = int(value) if value is not None else env.get_int("REPORT_MAX_ACTIVE_PER_USER", 10)
    except (TypeError, ValueError):
        parsed = env.get_int("REPORT_MAX_ACTIVE_PER_USER", 10)
    return max(1, min(parsed, 200))


# --------------------------------------------------------------------- creation
def create_report(request, *, report_type: str, fmt: str = "pdf",
                  filters: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    user = _account(request)
    if report_type not in generators.REPORT_TYPES:
        raise ApiError("validation_failed",
                        f"Unknown report type '{report_type}'.",
                        details={"report_types": sorted(generators.REPORT_TYPES)})
    spec = generators.REPORT_TYPES[report_type]
    if spec.get("administrator_only") and user.role != ADMINISTRATOR:
        raise ApiError("permission_denied",
                       f"{spec['label']} is restricted to administrators.")
    fmt = (fmt or "pdf").lower()
    if fmt not in FORMATS:
        raise ApiError("validation_failed", f"format must be one of: {', '.join(FORMATS)}.")

    raw_filters = dict(filters or {})
    try:
        # Fail fast on unusable filters so the requester learns immediately.
        generators.normalise_filters({**(spec.get("default_filters") or {}), **raw_filters})
    except generators.ReportDataError as exc:
        raise ApiError("validation_failed", str(exc)) from exc

    prune_expired()

    active = reports_repo.count({"requested_by": user.id, "status": {"$in": ["queued", "running"]}})
    if active >= max_active_per_user():
        raise ApiError("conflict",
                       f"{active} report(s) are already queued or running for this account. "
                       f"Wait for one to finish (limit {max_active_per_user()}).")

    moment = utcnow()
    document = {
        "report_type": report_type,
        "label": spec["label"],
        "format": fmt,
        "status": "queued",
        "requested_by": user.id,
        "requested_by_role": user.role,
        "filters": raw_filters,
        "download_name": None,
        "file_path": None,
        "file_size_bytes": None,
        "row_count": None,
        "insufficient_data": None,
        "reason": None,
        "error_message": None,
        "executor": None,
        "created_at": moment,
        "started_at": None,
        "completed_at": None,
        "expires_at": moment + timedelta(days=retention_days()),
        "download_count": 0,
        "schema_version": generators.SCHEMA_VERSION,
    }
    try:
        report_id = reports_repo.insert_one(document)
    except RepositoryError as exc:
        logger.error("Report request could not be stored: %s", exc)
        raise ApiError("internal_error", "The report request could not be stored.") from exc

    try:
        executor = tasks.submit(
            TASK_NAME,
            job_id=report_id,
            job_type="report",
            payload={"report_type": report_type, "format": fmt,
                     "filters": raw_filters, "requested_by": user.id},
        )
        reports_repo.update_by_id(report_id, {"executor": executor})
    except tasks.BackendUnavailable as exc:
        reports_repo.update_by_id(report_id, {
            "status": "failed",
            "error_message": "No background executor accepted the report task.",
            "completed_at": utcnow(),
        })
        logger.error("Report dispatch failed: %s", exc)
        raise ApiError("service_unavailable",
                       "Report generation is unavailable right now. Try again shortly.") from exc

    audit.for_request(
        request,
        action="report.requested",
        resource_type="report",
        resource_id=report_id,
        outcome="success",
        metadata={"report_type": report_type, "format": fmt, "executor": executor,
                  "filters": _safe_filters(raw_filters)},
    )
    document["executor"] = executor
    return public(_with_id(document, report_id), request=request)


def _safe_filters(filters: Dict[str, Any]) -> Dict[str, Any]:
    """Audit metadata only - never the whole payload, never anything secret."""
    summary: Dict[str, Any] = {}
    for key in ("metric", "frequency", "start_date", "end_date", "regions", "limit"):
        if key in filters:
            value = filters[key]
            summary[key] = value if not isinstance(value, (list, tuple)) else list(value)[:10]
    return summary


# ------------------------------------------------------------------ background
@tasks.register(TASK_NAME)
def generate_report(*, job_id: str, report_type: str, format: str = "pdf",  # noqa: A002
                    filters: Optional[Dict[str, Any]] = None,
                    requested_by: Optional[str] = None) -> Dict[str, Any]:
    """Registered task body. Claiming the document is atomic so double dispatch is inert.

    The claim is a conditional single-document update (``status: "queued"`` must match),
    which is what ``modified_count == 1`` means: this worker won the job. Note that
    ``Repository.find_one_and_update`` is not used because it imports ``pymongo.RETURN_*``
    constants that PyMongo 4 removed; the conditional update is equally atomic.
    """
    claimed = reports_repo.update_many(
        {"_id": to_object_id(job_id), "status": "queued"},
        {"status": "running", "started_at": utcnow()},
    )
    if not claimed:
        current = reports_repo.find_one({"_id": to_object_id(job_id)}, {"status": 1})
        if current is None:
            logger.warning("Report job %s no longer exists", job_id)
            return {"status": "missing"}
        logger.info("Report job %s already in status '%s'; not re-running",
                    job_id, current.get("status"))
        return {"status": current.get("status"), "skipped": True}

    claim = reports_repo.find_one({"_id": to_object_id(job_id)})
    actor = requested_by or str((claim or {}).get("requested_by") or "")
    try:
        artifact = generators.generate(report_type, filters or {})
    except generators.ReportDataError as exc:
        _fail(job_id, str(exc)[:500])
        audit.record(action="report.generation_failed", resource_type="report",
                     resource_id=job_id, actor_user_id=actor or None,
                     outcome="failure", metadata={"report_type": report_type,
                                                  "reason": str(exc)[:180]})
        return {"status": "failed", "reason": str(exc)}

    fmt = format if format in EXTENSIONS else "pdf"
    directory = REPORT_ROOT / job_id
    directory.mkdir(parents=True, exist_ok=True)
    internal = f"{secrets.token_hex(FILE_PREFIX_LENGTH)}.{EXTENSIONS[fmt]}"
    target = directory / internal
    try:
        written = generators.write(artifact, str(target), fmt)
    except Exception as exc:  # noqa: BLE001 - artefact writing must fail the job, not the server
        logger.error("Report artefact write failed for %s: %s", job_id, exc)
        _fail(job_id, f"The artefact could not be written: {str(exc)[:300]}")
        audit.record(action="report.generation_failed", resource_type="report",
                     resource_id=job_id, actor_user_id=actor or None, outcome="failure",
                     metadata={"report_type": report_type, "format": fmt,
                               "reason": str(exc)[:180]})
        return {"status": "failed", "reason": "artefact_write_failed"}

    completed = utcnow()
    updates = {
        "status": "generated",
        "completed_at": completed,
        "file_path": storage_paths.stored_key(target),
        "download_name": download_name(report_type, fmt, artifact, job_id),
        "file_size_bytes": int(written["file_size_bytes"]),
        "row_count": int(artifact["row_count"]),
        "artefact_rows_written": int(written["row_count"]),
        "columns": artifact["columns"],
        "title": artifact["title"],
        "insufficient_data": bool(artifact["insufficient_data"]),
        "reason": artifact.get("reason"),
        "generation_metadata": _generation_metadata(artifact),
        "error_message": None,
    }
    reports_repo.update_by_id(job_id, updates)
    audit.record(action="report.generated", resource_type="report", resource_id=job_id,
                 actor_user_id=actor or None,
                 outcome="success",
                 metadata={"report_type": report_type, "format": fmt,
                           "row_count": artifact["row_count"],
                           "file_size_bytes": updates["file_size_bytes"],
                           "insufficient_data": bool(artifact["insufficient_data"]),
                           "artefact_on_disk": target.is_file()})
    logger.info("Report %s generated (%d rows, %d bytes)", job_id,
                artifact["row_count"], updates["file_size_bytes"])
    return {"status": "generated", "row_count": artifact["row_count"],
            "file_size_bytes": updates["file_size_bytes"]}


def _fail(job_id: str, message: str) -> None:
    reports_repo.update_by_id(job_id, {"status": "failed", "error_message": message,
                                       "completed_at": utcnow()})


def _generation_metadata(artifact: Dict[str, Any]) -> Dict[str, Any]:
    metadata = artifact.get("metadata") or {}
    provenance = artifact.get("provenance") or {}
    return {
        "generation_timestamp": metadata.get("generation_timestamp"),
        "data_source": metadata.get("data_source"),
        "date_range": metadata.get("date_range"),
        "units": metadata.get("units"),
        "method": provenance.get("method"),
        "computed_from": provenance.get("computed_from"),
        "database_mode": provenance.get("database_mode"),
        "model_metadata": metadata.get("model_metadata"),
        "statement": provenance.get("statement"),
    }


def download_name(report_type: str, fmt: str, artifact: Dict[str, Any], job_id: str) -> str:
    stamp = ""
    try:
        stamp = datetime.strptime(str(artifact["metadata"]["generation_timestamp"])[:10],
                                  "%Y-%m-%d").strftime("%Y%m%d")
    except (KeyError, TypeError, ValueError):
        stamp = datetime.now(timezone.utc).strftime("%Y%m%d")
    return f"earthscape-{report_type}-{stamp}-{job_id[:8]}.{EXTENSIONS[fmt]}"


# -------------------------------------------------------------------- reading
def visible_query(request) -> Dict[str, Any]:
    user = _account(request)
    if user.role == ADMINISTRATOR:
        return {}
    return {"requested_by": user.id}


def list_reports(request, *, page: int, page_size: int, status: Optional[str] = None,
                 report_type: Optional[str] = None,
                 include_expired: bool = False) -> Dict[str, Any]:
    query = visible_query(request)
    if status:
        query["status"] = status
    if report_type:
        query["report_type"] = report_type
    if not include_expired:
        query["$or"] = [{"expires_at": None}, {"expires_at": {"$gte": utcnow()}}]
    page_data = reports_repo.paginate(query, page=page, page_size=page_size,
                                      sort=[("created_at", -1)])
    page_data["items"] = [public(document, request=request) for document in page_data["items"]]
    return page_data


def get_document(report_id: str) -> Dict[str, Any]:
    try:
        document = reports_repo.find_one({"_id": to_object_id(report_id)})
    except RepositoryError as exc:
        raise ApiError("not_found", "No such report.") from exc
    if document is None:
        raise ApiError("not_found", "No such report.")
    return document


def check_access(document: Dict[str, Any], request) -> str:
    """Returns the acting user id; raises when this report is not theirs."""
    user = _account(request)
    owner = str(document.get("requested_by") or "")
    if user.role == ADMINISTRATOR or owner == user.id:
        return user.id
    raise ApiError("permission_denied", "This report belongs to another account.")


def detail(report_id: str, request) -> Dict[str, Any]:
    document = get_document(report_id)
    check_access(document, request)
    return public(document, request=request, include_columns=True)


def cancel_report(report_id: str, request) -> Dict[str, Any]:
    """Withdraw a report that has not started yet.

    The worker claims a job with a conditional update on ``status: "queued"``, so moving
    the document to ``cancelled`` before the claim is a real cancellation, not a label.
    A report already generating is left alone: the PDF/CSV writer has no safe
    interruption point, and pretending otherwise would misreport what happened.
    """
    document = get_document(report_id)
    check_access(document, request)
    outcome = reports_repo.update_many(
        {"_id": to_object_id(report_id), "status": "queued"},
        {"status": "cancelled", "error_message": None,
         "cancelled_at": utcnow(), "cancelled_by": str(getattr(request.user, "id", ""))},
    )
    if not outcome:
        current = get_document(report_id).get("status")
        raise ApiError("conflict",
                       f"This report is '{current}'; only a queued report can be withdrawn.",
                       status=409)
    audit.for_request(request, action="report.cancelled", resource_type="report",
                      resource_id=report_id)
    return public(get_document(report_id), request=request)


def artefact_for_download(report_id: str, request) -> Tuple[Path, str, str, Dict[str, Any]]:
    """Access-checked path + filename. Never returns a path it has not verified."""
    document = get_document(report_id)
    actor = check_access(document, request)
    status = document.get("status")
    if status in ("queued", "running"):
        raise ApiError("service_unavailable",
                       "The report is still being generated.", status=409)
    if status == "failed":
        raise ApiError("not_found",
                       str(document.get("error_message") or "Generation failed."), status=409)
    raw_path = document.get("file_path")
    if not raw_path:
        raise ApiError("not_found", "No artefact was recorded for this report.", status=409)
    path = storage_paths.stored_path(raw_path)
    if not path.is_file():
        # The document says generated but the bytes are gone: report that, do not pretend.
        reports_repo.update_by_id(report_id, {
            "status": "failed",
            "error_message": "The artefact is no longer present on disk.",
            "file_path": None,
            "completed_at": utcnow(),
        })
        raise ApiError("not_found",
                       "The stored artefact is no longer present on disk (it may have been "
                       "removed or the local data directory reset).", status=410)
    expires = _as_datetime(document.get("expires_at"))
    if expires is not None and expires < utcnow():
        raise ApiError("not_found", "This report has passed its retention date.", status=410)

    reports_repo.update_by_id(report_id, {"$inc": {"download_count": 1}})
    audit.for_request(
        request,
        action="report.downloaded",
        resource_type="report",
        resource_id=report_id,
        outcome="success",
        metadata={"download_name": document.get("download_name"),
                  "file_size_bytes": path.stat().st_size},
    )
    return (path, str(document.get("download_name") or path.name),
            CONTENT_TYPES.get(str(document.get("format")), "application/octet-stream"),
            document)


def delete_report(report_id: str, request) -> Dict[str, Any]:
    document = get_document(report_id)
    user = _account(request)
    owner = str(document.get("requested_by") or "")
    if user.role != ADMINISTRATOR and owner != user.id:
        raise ApiError("permission_denied", "Only the requester or an administrator can "
                                            "remove a report.")
    removed_from_disk = False
    raw_path = document.get("file_path")
    if raw_path:
        path = storage_paths.stored_path(raw_path)
        if path.is_file():
            try:
                path.unlink()
                removed_from_disk = True
            except OSError as exc:
                logger.warning("Report artefact could not be removed (%s)", type(exc).__name__)
        _rmdir_if_empty(path.parent)
    deleted = reports_repo.delete_by_id(report_id)
    audit.for_request(request, action="report.deleted", resource_type="report",
                      resource_id=report_id, outcome="success" if deleted else "failure",
                      metadata={"artefact_removed": removed_from_disk,
                                "document_removed": bool(deleted)})
    return {"deleted": bool(deleted), "artefact_removed": removed_from_disk,
            "note": "The report document and its artefact (when present) were removed."}


def public(document: Dict[str, Any], *, request=None,
           include_columns: bool = False) -> Dict[str, Any]:
    status = document.get("status")
    expires = _as_datetime(document.get("expires_at"))
    expired = bool(expires is not None and expires < utcnow())
    payload = {
        "id": str(document.get("id") or document.get("_id")),
        "report_type": document.get("report_type"),
        "label": document.get("label"),
        "title": document.get("title"),
        "format": document.get("format"),
        "status": status,
        "requested_by": document.get("requested_by"),
        "requested_by_role": document.get("requested_by_role"),
        "filters": document.get("filters") or {},
        "download_name": document.get("download_name"),
        "file_size_bytes": document.get("file_size_bytes"),
        "row_count": document.get("row_count"),
        "insufficient_data": document.get("insufficient_data"),
        "reason": document.get("reason"),
        "error_message": document.get("error_message"),
        "executor": document.get("executor"),
        "download_count": document.get("download_count") or 0,
        "created_at": document.get("created_at"),
        "started_at": document.get("started_at"),
        "completed_at": document.get("completed_at"),
        "expires_at": document.get("expires_at"),
        "expired": expired,
        # Honest availability: generated AND the bytes are actually on disk AND in date.
        "download_available": (status == "generated" and not expired
                               and _file_exists(document.get("file_path"))),
        "download_url": None,
    }
    if include_columns:
        payload["columns"] = document.get("columns")
        payload["generation_metadata"] = document.get("generation_metadata")
    return payload


def counts(request) -> Dict[str, Any]:
    base = visible_query(request)
    out = {"by_status": {}, "by_type": {}, "retention_days": retention_days()}
    for status in STATUSES:
        query = dict(base)
        query["status"] = status
        out["by_status"][status] = reports_repo.count(query)
    for name in generators.REPORT_TYPES:
        query = dict(base)
        query["report_type"] = name
        out["by_type"][name] = reports_repo.count(query)
    out["total"] = reports_repo.count(base)
    return out


def catalogue(request) -> List[Dict[str, Any]]:
    entries = generators.catalogue()
    user = getattr(getattr(request, "user", None), "role", None)
    if user == ADMINISTRATOR:
        return entries
    return [{**entry, "available_to_you": False} for entry in entries
            if not entry.get("administrator_only")]


# ---------------------------------------------------------------------- upkeep
def prune_expired() -> Dict[str, Any]:
    """Enforce retention: remove expired artefacts and their documents.

    Runs at most once every ten minutes per process so that list/create calls do not
    turn into repeated filesystem sweeps.
    """
    global _LAST_PRUNE
    now = utcnow()
    if _LAST_PRUNE is not None and (now - _LAST_PRUNE).total_seconds() < PRUNE_INTERVAL_SECONDS:
        return {"skipped": True, "reason": "pruned recently"}
    _LAST_PRUNE = now
    removed_files = 0
    expired = reports_repo.find({"status": "generated", "expires_at": {"$lt": now}},
                                limit=500)
    for document in expired:
        path = document.get("file_path")
        if path:
            handle = storage_paths.stored_path(path)
            if handle.is_file():
                try:
                    handle.unlink()
                    removed_files += 1
                except OSError:
                    pass
            _rmdir_if_empty(handle.parent)
        reports_repo.update_by_id(str(document["_id"]), {
            "status": "expired",
            "file_path": None,
            "expired_at": now,
        })
    if expired:
        audit.record(action="report.retention_applied", resource_type="report",
                     outcome="success", metadata={"documents_expired": len(expired),
                                                  "artefacts_removed": removed_files})
    return {"documents_expired": len(expired), "artefacts_removed": removed_files}


def storage_report() -> Dict[str, Any]:
    """Real filesystem numbers for the administrator status surface."""
    root = Path(REPORT_ROOT)
    files = 0
    total_bytes = 0
    if root.is_dir():
        for handle in root.rglob("*"):
            if handle.is_file():
                files += 1
                try:
                    total_bytes += handle.stat().st_size
                except OSError:
                    continue
    return {"root": str(root), "exists": root.is_dir(), "artefact_files": files,
            "artefact_bytes": total_bytes, "retention_days": retention_days()}


# ----------------------------------------------------------------- small helpers
def _account(request):
    user = getattr(request, "user", None)
    if user is None or not getattr(user, "is_authenticated", False):
        raise ApiError("permission_denied", "Authentication required.", status=401)
    return user


def _with_id(document: Dict[str, Any], report_id: str) -> Dict[str, Any]:
    out = dict(document)
    out["id"] = report_id
    return out


def _file_exists(raw: Any) -> bool:
    if not raw:
        return False
    try:
        return storage_paths.stored_path(raw).is_file()
    except OSError:
        return False


def _rmdir_if_empty(directory: Path) -> None:
    try:
        if directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()
    except OSError:
        pass


def _as_datetime(value: Any) -> Optional[datetime]:
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    if isinstance(value, str):
        try:
            parsed = datetime.fromisoformat(value)
        except ValueError:
            return None
        return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)
    return None


def _setting_value(key: str) -> Any:
    document = platform_settings.find_one({"key": key}, {"value": 1})
    return document.get("value") if document else None
