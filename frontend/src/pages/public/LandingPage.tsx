function HeroTrend() {
  const trend = useAsync(() => api.climate.trend({ metric: 'temperature_c', frequency: 'monthly' }), [])

  return (
    <Panel
      title="Mean temperature, monthly"
      description="Live output of the analytics pipeline for every observation this deployment holds."
      actions={<RefreshButton onClick={() => void trend.refetch()} busy={trend.refreshing} />}
      footer={
        trend.data?.available && trend.data.point_count > 0 ? (
          <span>
            {formatCount(trend.data.point_count)} periods from {trend.data.last_period ?? '—'} backwards. Computed by the
            aggregation pipeline over stored station-day records — never illustrative.
          </span>
        ) : trend.error ? (
          <span>The chart above is a live query result; nothing is rendered in its place when the API does not answer.</span>
        ) : (
          <span>This chart appears as soon as ingestion produces enough stored observations.</span>
        )
      }
    >
      {trend.loading ? (
        <ChartSkeleton height={300} />
      ) : trend.error ? (
        <ErrorState error={trend.error} onRetry={() => void trend.refetch()} />
      ) : !trend.data || trend.data.available === false || trend.data.series.length === 0 ? (
        <EmptyState
          icon={<Activity className="h-5 w-5" />}
          title="No trend series yet"
          description={
            <>
              {trend.data?.reason ?? 'The analytics service has not been queried successfully, so no series can be shown.'}
              {trend.data && trend.data.available === false ? (
                <>
                  {' '}
                  Points available: {formatCount(trend.data.available_points ?? 0)} · points required:{' '}
                  {formatCount(trend.data.required_points ?? 0)}.
                </>
              ) : null}
            </>
          }
          action={
            <Link to="/login" className="btn btn-secondary btn-sm">
              Sign in to run ingestion
            </Link>
          }
        />
      ) : (
        <TrendChart
          series={trend.data.series}
          metric={trend.data.metric}
          unit={trend.data.unit}
          label={trend.data.label}
          variant="area"
          height={300}
          showCounts
        />
      )}
    </Panel>
  )
}

